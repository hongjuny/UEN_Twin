"""Exploratory experiment (NOT a demo scenario): cut one backbone link during the AI training campaign.

Each variant is ai_training_campaign with the same background traffic and seed, plus one link down from 09:00 to
11:00. The variant YAML files are written next to this script; results go to results.md. SIMULATED.

    uv run python experiments/ai_campaign_link_cuts/run.py
"""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd
import yaml

from uetn_twin import topology
from uetn_twin.engine import DEFAULT_OUT
from uetn_twin.sim.runner import SimRun
from uetn_twin.sim.scenario import load_scenario

HERE = Path(__file__).resolve().parent
LINKS = ["uvu-orem--richfield-dc", "slc-slcc--suu-cedar", "suu-cedar--tdc-stgeorge", "uvu-wasatch--usu-eastern"]
CUT, RESTORE = "09:00", "11:00"


def variant(link: str) -> dict:
    base = yaml.safe_load((HERE.parents[1] / "data" / "scenarios" / "ai_training_campaign.yaml").read_text())
    base["id"] = f"ai_campaign_cut_{link.replace('--', '__')}"
    base["title"] = f"Experiment: AI training campaign with {link} down {CUT}-{RESTORE}"
    base["notes"] = "Exploratory experiment, not a demo scenario. Same background and seed as ai_training_campaign."
    base["events"] = [{"at": CUT, "action": "set_link_state", "link": link, "up": False},
                      {"at": RESTORE, "action": "set_link_state", "link": link, "up": True}]
    return base


def summarize(out: Path, sites: dict[str, int], telemetry_s: float) -> dict:
    links = pd.read_parquet(out / "link_telemetry.parquet")
    nodes = pd.read_parquet(out / "node_telemetry.parquet")
    totals = pd.read_parquet(out / "totals.parquet")
    top = links.loc[links.utilization.idxmax()]
    over = links[links.utilization > 1.0].groupby("direction").agg(peak=("utilization", "max"), n=("sim_s", "count"))
    nodes["sites"] = nodes.node_id.map(sites).fillna(0) * nodes.unreachable
    unreachable_sites = nodes.groupby("sim_s").sites.sum().max()
    return dict(
        max_link=f"{top.direction} {top.utilization:.0%} at {top.t[11:16]}",
        overloaded="; ".join(f"{d} peak {r.peak:.0%}, {r.n * telemetry_s / 60:.0f} min" for d, r in
                             over.sort_values("peak", ascending=False).iterrows()) or "none",
        dropped_gb=float(totals.dropped_gbps.sum() * telemetry_s),  # Gbps x s = gigabits
        unreachable_sites=int(unreachable_sites),
    )


def main() -> None:
    topo = topology.load()
    sites = {g.parent: g.k12_sites + g.higher_ed_sites + g.healthcare_sites for g in topo.sites}
    rows = []
    base = SimRun(load_scenario("ai_training_campaign"), out_base=DEFAULT_OUT / "experiments", topo=topo)
    rows.append(dict(variant="no cut (ai_training_campaign)", **summarize(base.run(), sites, base.telemetry_s)))
    for link in LINKS:
        path = HERE / f"cut_{link.replace('--', '__')}.yaml"
        path.write_text("# Generated by run.py. Exploratory experiment, not a demo scenario.\n"
                        + yaml.safe_dump(variant(link), sort_keys=False, allow_unicode=True))
        run = SimRun(load_scenario(path), out_base=DEFAULT_OUT / "experiments", topo=topo)
        rows.append(dict(variant=f"{link} down {CUT}-{RESTORE}", **summarize(run.run(), sites, run.telemetry_s)))
    df = pd.DataFrame(rows)
    lines = ["# Experiment: link cuts during the AI training campaign (SIMULATED)", "",
             "Not a demo scenario. Background traffic and seed are those of `ai_training_campaign`; one link is down",
             f"from {CUT} to {RESTORE}. Utilization is offered load (30 s averages); dropped traffic is the total over",
             "the run in gigabits; unreachable sites is the largest number of schools/clinics cut off at once.", "",
             "| variant | most utilized direction | directions above 100% (peak, time above) | dropped (Gb) | unreachable sites |",
             "|---|---|---|---|---|"]
    lines += [f"| {r.variant} | {r.max_link} | {r.overloaded} | {r.dropped_gb:,.0f} | {r.unreachable_sites} |"
              for r in df.itertuples()]
    (HERE / "results.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(json.dumps({"written": str((HERE / "results.md").relative_to(HERE.parents[1]))}))


if __name__ == "__main__":
    main()
